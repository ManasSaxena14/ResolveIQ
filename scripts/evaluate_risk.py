"""Score the escalation risk models once on the test split.

Writes to results/risk/:

- metrics.json and comparison.md (model table and cost table)
- precision_recall.png, calibration.png and shap_summary.png
- feature_importance.csv (mean absolute SHAP value per feature)
- example_explanations.md (top reasons for the highest and lowest risk tickets)

Thresholds are never tuned here: each one was chosen on the validation split.

Usage:
    python scripts/evaluate_risk.py [--config PATH] [--no-mlflow]
"""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import asdict
from pathlib import Path

import joblib
import numpy as np

from resolveiq.classifier.data import load_split
from resolveiq.config import load_config
from resolveiq.risk.evaluate import (
    alert_stats,
    binary_metrics,
    cost_table,
    plot_precision_recall,
    plot_probability_calibration,
)
from resolveiq.risk.explain import (
    global_importance,
    plot_shap_summary,
    shap_values,
    text_model_terms,
    top_reasons,
)
from resolveiq.risk.features import load_feature_schema, load_feature_split
from resolveiq.risk.predict import META_FILENAME, RiskModel
from resolveiq.risk.train import TreeModel, load_booster
from resolveiq.tracking import tracked_run

LOGISTIC_FILENAME = "logistic_baseline.joblib"
DEFAULT_XGBOOST_FILENAME = "xgboost_default.json"

MODEL_NAMES = {
    "majority": "Always predict the training escalation rate",
    "logistic_regression": "Logistic regression",
    "xgboost": "XGBoost, starting parameters",
    "xgboost_tuned": "XGBoost, tuned",
    "xgboost_tuned_calibrated": "XGBoost, tuned and calibrated",
}


def _tree(path: Path, names: list[str]) -> TreeModel:
    return TreeModel(load_booster(path), names, {}, 0, 0.0)


def write_comparison(path: Path, metrics: dict, costs: list, meta: dict, alert: dict) -> None:
    target = round(meta["precision_target"] * 100)
    lines = [
        "# Escalation risk model: test results",
        "",
        f"Generated by `scripts/evaluate_risk.py` on the test split ({metrics['test_size']} "
        f"tickets, escalation rate {metrics['test_positive_rate']:.1%}).",
        "",
        "Label: priority is high (a proxy; the dataset has no escalation field).",
        "",
        f"| Model | PR-AUC | Recall at {target}% precision | Brier score | ROC-AUC |",
        "|---|---|---|---|---|",
    ]
    for key, name in MODEL_NAMES.items():
        m = metrics["models"][key]
        lines.append(
            f"| {name} | {m['pr_auc']:.4f} | {m['recall_at_precision']:.4f} | "
            f"{m['brier']:.4f} | {m['roc_auc']:.4f} |"
        )
    lines += [
        "",
        "## Alert threshold under different cost assumptions",
        "",
        "Each threshold minimizes total cost on the validation split; the other columns",
        "are measured on the test split.",
        "",
        "| Cost of a miss : cost of a false alarm | Chosen threshold | Escalations caught | "
        "False alarms per 100 alerts | Tickets alerted |",
        "|---|---|---|---|---|",
    ]
    for row in costs:
        lines.append(
            f"| {row.cost_ratio:g} : 1 | {row.threshold:.2f} | {row.caught:.1%} | "
            f"{row.false_alarms_per_100_alerts:.1f} | {row.alert_rate:.1%} |"
        )
    lines += [
        "",
        f"Production threshold: {alert['threshold']:.2f} (cost ratio "
        f"{meta['alert_cost_ratio']:g} : 1). On the test split it catches "
        f"{alert['caught']:.1%} of escalations, alerts on {alert['alert_rate']:.1%} of tickets "
        f"and raises {alert['false_alarms_per_100_alerts']:.1f} false alarms per 100 alerts.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_examples(path: Path, examples: list[dict]) -> None:
    lines = [
        "# Example explanations",
        "",
        "The five test tickets with the highest and the three with the lowest calibrated",
        "escalation probability, with the reasons returned by the model. Subjects come from",
        "the synthetic public dataset and are already masked.",
        "",
    ]
    for example in examples:
        reasons = "; ".join(example["reasons"]) or "No feature raises the score"
        lines += [
            f"**{example['subject']}**",
            "",
            f"- Probability {example['probability']:.2f}, alert: "
            f"{'yes' if example['alert'] else 'no'}, actual priority: {example['priority']}",
            f"- Ticket type {example['ticket_type']}, queue {example['queue']}",
            f"- Reasons: {reasons}",
            "",
        ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", help="Path to a config file")
    parser.add_argument("--no-mlflow", action="store_true")
    args = parser.parse_args()

    settings = load_config(args.config)
    if args.no_mlflow:
        settings.tracking.enabled = False
    cfg = settings.risk
    features_dir = settings.resolve(cfg.features_dir)
    model_dir = settings.resolve(cfg.output_dir)
    results_dir = settings.resolve(settings.paths.results_dir) / "risk"
    results_dir.mkdir(parents=True, exist_ok=True)

    schema = load_feature_schema(features_dir)
    names = schema.names
    meta = json.loads((model_dir / META_FILENAME).read_text(encoding="utf-8"))
    meta["precision_target"] = cfg.precision_target
    model = RiskModel.load(model_dir)
    x_val, y_val, _ = load_feature_split(features_dir, "validation")
    x_test, y_test, test_ids = load_feature_split(features_dir, "test")

    tuned = _tree(model_dir / "xgboost.json", names)
    raw_test = tuned.predict(x_test)
    calibrated_test = model.calibrator.transform(raw_test)
    calibrated_val = model.calibrator.transform(tuned.predict(x_val))
    scores = {
        "majority": np.full(len(y_test), meta["train_positive_rate"]),
        "logistic_regression": joblib.load(model_dir / LOGISTIC_FILENAME).predict_proba(x_test)[
            :, 1
        ],
        "xgboost": _tree(model_dir / DEFAULT_XGBOOST_FILENAME, names).predict(x_test),
        "xgboost_tuned": raw_test,
        "xgboost_tuned_calibrated": calibrated_test,
    }
    target = cfg.precision_target
    metrics = {
        "test_size": len(y_test),
        "test_positive_rate": round(float(y_test.mean()), 4),
        "models": {key: binary_metrics(y_test, value, target) for key, value in scores.items()},
    }
    costs = cost_table(y_val, calibrated_val, y_test, calibrated_test, cfg.cost_ratios)
    alert = asdict(alert_stats(y_test, calibrated_test, model.threshold))
    metrics["cost_table"] = [row.as_dict() for row in costs]
    metrics["production_threshold"] = model.threshold
    metrics["production_alert"] = alert

    plot_precision_recall(
        y_test,
        {MODEL_NAMES[k]: scores[k] for k in ("logistic_regression", "xgboost", "xgboost_tuned")},
        results_dir / "precision_recall.png",
        "Escalation risk: precision-recall on the test split",
    )
    plot_probability_calibration(
        y_test,
        {"XGBoost, raw scores": raw_test, "XGBoost, calibrated": calibrated_test},
        results_dir / "calibration.png",
        "Escalation risk: calibration on the test split",
    )
    contributions = shap_values(tuned.booster, x_test, names)
    plot_shap_summary(contributions, x_test, names, results_dir / "shap_summary.png")
    importance = global_importance(contributions, names)
    with (results_dir / "feature_importance.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["feature", "mean_abs_shap"])
        writer.writerows(importance)
    metrics["top_features"] = importance[:10]

    data_dir = settings.resolve(settings.classifier.processed_dir)
    tickets = {t.ticket_id: t for t in load_split(data_dir, "test")}
    order = np.argsort(-calibrated_test)
    examples = []
    for index in [*order[:5], *order[-3:]]:
        ticket = tickets[test_ids[index]]
        terms = text_model_terms(model.text_model, ticket.text) if model.text_model else []
        reasons = top_reasons(
            contributions[index],
            x_test[index],
            schema,
            ticket.text,
            ticket.ticket_type,
            text_terms=terms,
        )
        examples.append(
            {
                "subject": ticket.text.split("\n", 1)[0][:90],
                "probability": float(calibrated_test[index]),
                "alert": bool(calibrated_test[index] >= model.threshold),
                "priority": ticket.priority,
                "ticket_type": ticket.ticket_type,
                "queue": ticket.label,
                "reasons": [r.text for r in reasons],
            }
        )
    write_examples(results_dir / "example_explanations.md", examples)

    (results_dir / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    write_comparison(results_dir / "comparison.md", metrics, costs, meta, alert)

    with tracked_run(settings, "escalation-risk", run_name="evaluation-test") as mlflow:
        if mlflow:
            for key, values in metrics["models"].items():
                mlflow.log_metrics({f"test_{key}_{m}": v for m, v in values.items()})
            mlflow.log_metrics({f"test_alert_{k}": v for k, v in alert.items()})
            mlflow.log_artifacts(str(results_dir), artifact_path="results")

    print((results_dir / "comparison.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
